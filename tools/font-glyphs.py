#!/usr/bin/env python3
"""Rebuild src/packages/ui/font-glyphs.js from the bundled faces.

The tests read that file to prove that every character in src/ can be drawn
by a bundled font. It records the cmap of each .woff2 in src/assets, so it
must be regenerated whenever a face is added, replaced or re-subset:

    python3 tools/font-glyphs.py

Requires fontTools with brotli (`pip install fonttools brotli`).

How the bundled faces were subset (for the record; run again by hand if the
faces are ever rebuilt):

  w95-symbols.woff2       DejaVu Sans, ASCII + Latin-1 + Latin Extended-A +
                          every code point the UI font (W95FA/Roboto) cannot
                          draw itself (Latin Extended-A keeps the Polish
                          dates the clock can print out of system fonts)
  w95-symbols-tech.woff2  DejaVu Sans Mono, U+2315 only - the magnifier glyph
                          is in the mono face but not the proportional one
  w95-serif.woff2         Liberation Serif, ASCII + Latin-1 + general punctuation
  w95-mono.woff2          Liberation Mono, ASCII + Latin-1 + box drawing

The DejaVu and Liberation names are reserved by their licences, so each
subset is renamed inside the font before it ships. See FONT-LICENSES.md.
"""
import pathlib
import sys

try:
    from fontTools.ttLib import TTFont
except ImportError:
    sys.exit('fontTools is not installed: pip install fonttools brotli')

ROOT = pathlib.Path(__file__).resolve().parent.parent
FACES = [
    ('W95FA', 'w95fa.woff2'),
    ('Roboto', 'roboto-regular-ascii.woff2'),
    ("WenQuanYi Bitmap Song 12px", 'wqy-song.woff2'),
    ('W95 Symbols', 'w95-symbols.woff2'),
    ('W95 Symbols', 'w95-symbols-tech.woff2'),
    ('W95 Serif', 'w95-serif.woff2'),
    ('W95 Mono', 'w95-mono.woff2'),
]


def ranges(points):
    out, low, prev = [], None, None
    for point in sorted(points):
        if low is None:
            low = prev = point
            continue
        if point == prev + 1:
            prev = point
            continue
        out.append([low, prev])
        low = prev = point
    if low is not None:
        out.append([low, prev])
    return out


def main():
    coverage = {}
    for family, name in FACES:
        path = ROOT / 'src' / 'assets' / name
        coverage.setdefault(family, set()).update(TTFont(path).getBestCmap())
    lines = [
        '// Generated by tools/font-glyphs.py - rerun it after changing any .woff2 in src/assets.',
        '// Each entry lists the inclusive code-point ranges the face can draw.',
        'export const FONT_GLYPHS = {',
    ]
    for family in sorted(coverage):
        spans = ','.join('[%d,%d]' % (low, high) for low, high in ranges(coverage[family]))
        lines.append('    %r: [%s],' % (family, spans))
    lines.append('};')
    (ROOT / 'src' / 'packages' / 'ui' / 'font-glyphs.js').write_text('\n'.join(lines) + '\n')
    print('wrote src/packages/ui/font-glyphs.js')


if __name__ == '__main__':
    main()
